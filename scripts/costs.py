"""Cost per episode / per user per month / at scale, computed from REAL runs in output/usage_log.json.

Uses the last log entry of every finished episode (status=done, defenses=all, cache on, skeptic full).
Writes output/costs.md.

    python scripts/costs.py --episodes-per-month 20
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from config import TTS_USD_PER_1K_CHARS, WORDS_PER_MINUTE  # noqa: E402

OUT = ROOT / "output"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--episodes-per-month", type=int, default=20, help="one episode per workday commute")
    a = ap.parse_args()
    log = json.loads((OUT / "usage_log.json").read_text())
    last: dict[str, dict] = {}
    for r in log:
        last[r["episode_id"]] = r
    done = [r for r in last.values() if r.get("status") == "done" and r.get("defenses", "code+design+prompt") == "code+design+prompt"
            and r.get("cache", True) and r.get("skeptic", "full") == "full"]
    by_len: dict[int, list[dict]] = {}
    for r in done:
        by_len.setdefault(r["minutes"], []).append(r)

    lines = ["# What Loremaster costs to run", "",
             f"From **{len(done)} real finished episodes** in `output/usage_log.json` (gpt-6-luna; prompt caching on; full Skeptic). "
             "Generated by `python scripts/costs.py`.", "",
             "| Length | Episodes measured | Avg input tok | Avg cached | Avg output tok | **Avg cost / episode** | Min–max |",
             "|---|---|---|---|---|---|---|"]
    per_ep = {}
    for m in sorted(by_len):
        rs = by_len[m]
        tok = lambda k: mean(sum(ag[k] for ag in r["agents"]) for r in rs)  # noqa: E731
        costs = [r["total_usd"] for r in rs]
        per_ep[m] = mean(costs)
        lines.append(f"| {m} min | {len(rs)} | {tok('input_tokens'):,.0f} | {tok('cached_tokens'):,.0f} | {tok('output_tokens'):,.0f} | "
                     f"**${per_ep[m]:.4f}** | ${min(costs):.4f}–${max(costs):.4f} |")

    # agent share
    share: dict[str, float] = {}
    for r in done:
        for ag in r["agents"]:
            share[ag["agent"]] = share.get(ag["agent"], 0) + ag["cost_usd"]
    tot = sum(share.values()) or 1
    lines += ["", "**Where the money goes (all measured episodes):** " +
              ", ".join(f"{k} {100*v/tot:.0f}%" for k, v in sorted(share.items(), key=lambda kv: -kv[1]))]

    n = a.episodes_per_month
    base_len = 20 if 20 in per_ep else max(per_ep)
    c = per_ep[base_len]
    tts_per_ep = base_len * WORDS_PER_MINUTE * 6 / 1000 * TTS_USD_PER_1K_CHARS  # ~6 chars per word
    lines += ["", f"## Per user and at scale (assumption: {n} × {base_len}-min episodes per user per month, one per workday commute)", "",
              "| Users | LLM only (browser voice) / month | + natural voice (OpenAI TTS, estimate) / month |", "|---|---|---|"]
    for users in (1, 100, 10_000):
        lines.append(f"| {users:,} | ${c * n * users:,.2f} | ${(c + tts_per_ep) * n * users:,.2f} |")
    lines += ["", f"- LLM cost per {base_len}-min episode: **${c:.4f}**. TTS estimate per episode: ${tts_per_ep:.3f} "
              f"(~{base_len * WORDS_PER_MINUTE:,} words ≈ {base_len * WORDS_PER_MINUTE * 6 / 1000:.0f}K chars at ~${TTS_USD_PER_1K_CHARS}/1K chars, "
              "an estimate since the course key has no TTS).",
              "- The takeaway: the *thinking* is cheap and the *voice* is the expensive part. That's why the browser voice is the default "
              "and generated audio is cached on disk, so a replay costs $0.",
              "- Guardrails cap the worst case: $0.05 per episode hard stop, 5 new episodes per 10 minutes per client."]
    (OUT / "costs.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
