"""Run the 4 Safety Lab demos with defenses ON and OFF; write output/safety_results.json + .md.

    python scripts/safety_test.py                 # all demos, ON and OFF
    python scripts/safety_test.py --demo poisoned_page --defenses all
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

import safety  # noqa: E402

OUT = ROOT / "output"


def to_md(results: list[dict]) -> str:
    lines = ["# Safety Lab results", "",
             "Each attack runs twice: **defenses ON** (all three layers: code, design, prompt) and **OFF** (none).",
             "Generated by `python scripts/safety_test.py`. Costs are real gpt-6-luna usage.", "",
             "| Demo | Defenses | Blocked? | What happened | Cost |", "|---|---|---|---|---|"]
    for r in results:
        lines.append(f"| {r['demo']} | {'ON' if r['defenses'] == 'all' else 'OFF'} | {'✅ yes' if r['blocked'] else '❌ no'} "
                     f"| {r['summary']} | ${r.get('cost_usd', 0):.5f} |")
    for r in results:
        lines += ["", f"## {r['demo']} · defenses {'ON' if r['defenses'] == 'all' else 'OFF'}", "", r.get("description", "")]
        for c in r.get("claims", []):
            lines.append(f"- **{c['grade']}**: {c['text']} ({c['note']})")
        for c in r.get("cases", []):
            lines.append(f"- {'allowed' if c['allowed'] else 'REFUSED'} [{c['layer']}] {c['topic']}: {c['reason']}")
        if r.get("quarantined"):
            lines.append("- Quarantined by the code layer:")
            lines += [f"  - `{q[:160]}`" for q in r["quarantined"]]
        if r.get("attack_markers_in_narration") is not None:
            lines.append(f"- Attack text found in narration: {r['attack_markers_in_narration'] or 'none'}")
        if r.get("narration_excerpt"):
            lines.append(f"- Narration excerpt: > {r['narration_excerpt'][:500]}…")
        if r.get("stop_reason"):
            lines.append(f"- Stop reason: {r['stop_reason']}")
    return "\n".join(lines) + "\n"


async def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--demo", choices=list(safety.RUNNERS))
    ap.add_argument("--defenses", choices=["all", "none"])
    a = ap.parse_args()
    demos = [a.demo] if a.demo else list(safety.RUNNERS)
    modes = [a.defenses] if a.defenses else ["all", "none"]
    results = []
    for d in demos:
        for m in modes:
            if d == "budget_cap" and m == "none":
                continue  # "off" would just be a normal $0.05 episode; the ON run is the demo
            print(f"running {d} defenses={m} …", flush=True)
            r = await safety.run_demo(d, m)
            print("  →", "BLOCKED" if r["blocked"] else "GOT THROUGH", "|", r["summary"], flush=True)
            results.append(r)
    OUT.mkdir(exist_ok=True)
    (OUT / "safety_results.json").write_text(json.dumps(results, indent=1, ensure_ascii=False))
    (OUT / "safety_results.md").write_text(to_md(results))
    print("wrote output/safety_results.json and .md")


if __name__ == "__main__":
    asyncio.run(main())
