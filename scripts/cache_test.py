"""Prompt-cache test: the same 3 episodes (10 min, auto branch) WITH cache vs WITHOUT cache.

WITH: stable prefix (house rules [+ style guide] + role prompt) and a fixed prompt_cache_key per agent.
WITHOUT: a random cache-buster line is the FIRST line of the instructions on every model call, so no two calls
share a prefix. A "without" run that still reports cached tokens is INVALID (HW6 lesson).

    python scripts/cache_test.py
"""

from __future__ import annotations

import asyncio
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

import pipeline  # noqa: E402
from models import EpisodeRequest  # noqa: E402

THREADS = ["republic-galactic-empire", "rome-imperium", "texas-law-medieval-spain"]
OUT = ROOT / "output"


async def run_one(thread: str, cache: bool) -> dict:
    req = EpisodeRequest(thread_id=thread, minutes=10)
    run = pipeline.new_run(req, auto_choose=True, cache=cache)
    t0 = time.time()
    await pipeline.start(run, req)
    ep = run.episode
    agents = [u.model_dump() for u in ep.usage]
    tot = {k: sum(a[k] for a in agents) for k in ("requests", "input_tokens", "cached_tokens", "cache_write_tokens", "output_tokens")}
    return {"setup": "with_cache" if cache else "without_cache", "thread": thread, "episode_id": ep.id, "status": ep.status,
            "chapters": len(ep.chapters), "seconds": round(time.time() - t0, 1), "cost_usd": ep.total_usd, **tot, "agents": agents}


def md(rows: list[dict]) -> str:
    def agg(setup):
        r = [x for x in rows if x["setup"] == setup]
        s = {k: sum(x[k] for x in r) for k in ("requests", "input_tokens", "cached_tokens", "cache_write_tokens", "output_tokens", "cost_usd", "seconds")}
        s["n"] = len(r)
        return s
    w, wo = agg("with_cache"), agg("without_cache")
    valid = wo["cached_tokens"] == 0
    saved = (1 - w["cost_usd"] / wo["cost_usd"]) * 100 if wo["cost_usd"] else 0
    lines = ["# Prompt cache test (gpt-6-luna, real API usage)", "",
             f"Same 3 episodes (10 min = 2 chapters, auto-picks branch 1) run **with** and **without** prompt caching. "
             f"Generated by `python scripts/cache_test.py`.", "",
             f"**Without-cache run valid: {'YES, 0 cached tokens reported' if valid else 'NO (cached tokens > 0, INVALID)'}**", "",
             "| | with cache | without cache |", "|---|---|---|"]
    for k, label in [("requests", "Model calls"), ("input_tokens", "Input tokens"), ("cached_tokens", "└ cached reads ($0.01/1M)"),
                     ("cache_write_tokens", "└ cache writes ($0.125/1M)"), ("output_tokens", "Output tokens ($0.50/1M)"),
                     ("seconds", "Wall-clock seconds")]:
        lines.append(f"| {label} | {w[k]:,} | {wo[k]:,} |")
    lines.append(f"| **Total cost (3 episodes)** | **${w['cost_usd']:.5f}** | **${wo['cost_usd']:.5f}** |")
    lines.append(f"| **Cost per episode** | **${w['cost_usd']/max(w['n'],1):.5f}** | **${wo['cost_usd']/max(wo['n'],1):.5f}** |")
    lines += ["", f"**Caching saved {saved:.1f}%** of the cost.", "", "## Per episode", "",
              "| Setup | Thread | Calls | Input | Cached | Cache write | Output | Cost | Seconds |", "|---|---|---|---|---|---|---|---|---|"]
    for x in rows:
        lines.append(f"| {x['setup']} | {x['thread']} | {x['requests']} | {x['input_tokens']:,} | {x['cached_tokens']:,} | "
                     f"{x['cache_write_tokens']:,} | {x['output_tokens']:,} | ${x['cost_usd']:.5f} | {x['seconds']} |")
    lines += ["", "Note: OpenAI bills cache **writes** at 1.25× the input price, so without a cache every call pays the "
              "write rate on its whole prefix, which is why the no-cache run costs more than plain input pricing would suggest."]
    return "\n".join(lines) + "\n"


async def main() -> None:
    rows = []
    for cache in (True, False):
        for t in THREADS:
            print(f"{'with' if cache else 'without'} cache · {t} …", flush=True)
            r = await run_one(t, cache)
            print(f"   ${r['cost_usd']:.5f}  cached={r['cached_tokens']}  write={r['cache_write_tokens']}  {r['seconds']}s", flush=True)
            rows.append(r)
    OUT.mkdir(exist_ok=True)
    (OUT / "cache_test.json").write_text(json.dumps(rows, indent=1))
    (OUT / "cache_test.md").write_text(md(rows))
    print("wrote output/cache_test.json and .md")


if __name__ == "__main__":
    asyncio.run(main())
